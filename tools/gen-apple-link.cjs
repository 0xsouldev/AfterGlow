// Writes assets/apple-link.js: the Apple Music link code that the bookmark loads from the site, so it updates itself.
// Generated from bookmarkletFor() in assets/app.js. Run with --check to only verify it is up to date (used in CI).
const fs = require('fs'), path = require('path');
const app = fs.readFileSync(path.join(__dirname, '../assets/app.js'), 'utf8');
const start = app.indexOf('function bookmarkletFor(url)'), end = app.indexOf('\n}\n', start) + 2;
if (start < 0) throw new Error('bookmarkletFor not found');
const bookmarkletFor = new Function(app.slice(start, end) + '; return bookmarkletFor;')();
const body = `/* Afterglow ↔ Apple Music link (generated by tools/gen-apple-link.cjs, do not edit). Loaded by the Afterglow bookmark. */\nwindow.__agOK=true;window.__agVia='live';\n${bookmarkletFor(null)};\n`;
const out = path.join(__dirname, '../assets/apple-link.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== body) { console.error('assets/apple-link.js is out of date: run node tools/gen-apple-link.cjs'); process.exit(1); }
  console.log('apple-link.js up to date');
} else { fs.writeFileSync(out, body); console.log('wrote', out, body.length, 'bytes'); }
